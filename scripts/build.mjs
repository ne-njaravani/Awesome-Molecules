import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const read = file => readFileSync(resolve(root, file), 'utf8');
const html = read('dist/index.html');
const css = read('dist/styles.css');
const js = read('dist/app.js');
const worker = read('worker/gateway.mjs');

for (const asset of ['index.html', 'styles.css', 'app.js']) {
  if (!read(`dist/${asset}`).trim()) throw new Error(`Missing ${asset}`);
}
const output = resolve(root, 'dist/server/index.js');
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output,
  `// Generated by npm run build. Edit worker/gateway.mjs and dist assets instead.\n` +
  worker + '\n' +
  `const STATIC_ASSETS = ${JSON.stringify({ html, css, js })};\n` +
  `export default { fetch(request, env) { return handleRequest(request, env, STATIC_ASSETS); } };\n`,
  'utf8');
console.log(`Built self-contained Worker: ${output}`);
